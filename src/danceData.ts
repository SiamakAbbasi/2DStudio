const slug = (value: string) =>
  `dance_${value
    .toLowerCase()
    .replaceAll(/[^a-z0-9]+/g, "_")
    .replace(/^_|_$/g, "")}`;
const point = (cx: number, cy: number, length: number, angle: number) => ({
  x: cx + Math.cos(angle) * length,
  y: cy + Math.sin(angle) * length,
});
function dancePose(style: string, name: string, index: number): Pose {
  const p = basePose(360, 720),
    seed = index + Object.keys(danceStyles).indexOf(style) * 11,
    floor =
      /Floor|Freeze|Handstand|Headstand|Crab|Spin Pose|Cartwheel|Split/.test(
        name,
      ),
    ballet =
      /Ballet|Arabesque|Attitude|Leg Extension|Position|Elegant|Leap/.test(
        name,
      ),
    robot = /Robot|Mechanical|Lock|Box Arms|90 Degree|Chest/.test(name),
    lean = ((seed % 7) - 3) * 13,
    spread = 55 + (seed % 5) * 18;
  p.torso.x += lean;
  p.neck.x += lean * 1.3;
  p.head.x += lean * 1.5;
  const ls = p.leftShoulder,
    rs = p.rightShoulder;
  const la = robot
      ? Math.PI + ((seed % 4) * Math.PI) / 2
      : -2.65 + (seed % 6) * 0.42,
    ra = robot ? ((seed % 4) * Math.PI) / 2 : -0.5 - (seed % 7) * 0.38;
  p.leftElbow = point(ls.x, ls.y, 75, la);
  p.leftWrist = point(
    p.leftElbow.x,
    p.leftElbow.y,
    72,
    la + (robot ? 0 : ((seed % 3) - 1) * 0.7),
  );
  p.rightElbow = point(rs.x, rs.y, 75, ra);
  p.rightWrist = point(
    p.rightElbow.x,
    p.rightElbow.y,
    72,
    ra + (robot ? 0 : ((seed % 4) - 1.5) * 0.55),
  );
  p.leftHip = { x: 360 - spread / 2, y: 720 };
  p.rightHip = { x: 360 + spread / 2, y: 720 };
  const legLift = /Kick|Extension|Arabesque|Attitude|One Leg|Balance/.test(
      name,
    ),
    lAng = 1.55 + ((seed % 5) - 2) * 0.22,
    rAng = legLift ? -0.15 - (seed % 3) * 0.25 : 1.55 - ((seed % 5) - 2) * 0.2;
  p.leftKnee = point(p.leftHip.x, p.leftHip.y, 92, lAng);
  p.leftAnkle = point(
    p.leftKnee.x,
    p.leftKnee.y,
    98,
    lAng + ((seed % 3) - 1) * 0.18,
  );
  p.rightKnee = point(p.rightHip.x, p.rightHip.y, 92, rAng);
  p.rightAnkle = point(
    p.rightKnee.x,
    p.rightKnee.y,
    98,
    rAng + (legLift ? -0.2 : ((seed % 3) - 1) * 0.18),
  );
  if (ballet) {
    p.leftWrist.y -= 45;
    p.rightWrist.y -= 45;
    p.leftAnkle.x -= 20;
    p.rightAnkle.x += 25;
  }
  if (floor) {
    for (const j of Object.keys(p) as JointName[]) {
      const q = p[j],
        x = q.x - 360,
        y = q.y - 720;
      q.x = 360 + y * 0.8;
      q.y = 805 + x * 0.45;
    }
    p.root = {
      x: (p.leftHip.x + p.rightHip.x) / 2,
      y: (p.leftHip.y + p.rightHip.y) / 2,
    };
  }
  return p;
}
