export const danceActions: Action[] = specs.map(
  ([
    name,
    style,
    entry,
    main,
    beats,
    intensity,
    loopable = false,
    rotation,
  ]) => {
    const entryPose = slug(entry),
      mainPose = slug(main),
      duration = beats * 0.5;
    return {
      id: slug(name),
      name,
      categories: ["Dance"],
      subcategory: style,
      style,
      tags: ["dance", style.toLowerCase(), name.toLowerCase()],
      participants: /Partner|Slow Dance/.test(name)
        ? ["actor", "actor"]
        : ["actor"],
      duration,
      beats,
      bars: beats / 4,
      intensity,
      loopable,
      entryPose,
      mainPose,
      exitPose: entryPose,
      keyframes: [
        {
          time: 0,
          pose: entryPose,
          easing: style === "Robot / Popping" ? "hold" : "ease-in-out",
        },
        {
          time: duration / 2,
          pose: mainPose,
          easing: style === "Robot / Popping" ? "snap" : "ease-in-out",
          ...(/Leap|Jump/.test(name) ? { dy: -180 } : {}),
        },
        {
          time: duration,
          pose: entryPose,
          easing: style === "Robot / Popping" ? "linear" : "ease-in-out",
          ...(rotation ? { rootRotation: rotation } : {}),
          ...(/Travel|Walk/.test(name)
            ? { dx: 220 }
            : /Leap/.test(name)
              ? { dx: 180 }
              : {}),
        },
      ],
    };
  },
);
